/* --------------------------------------------------------------------------
   Derived lookups and helpers
   -------------------------------------------------------------------------- */
export const CATEGORY_MAP = Object.fromEntries(
  CATEGORIES.map((category) => [category.id, category]),
);

export const getExperiment = (id) =>
  EXPERIMENTS.find((experiment) => experiment.id === id) ?? null;

export const getCategory = (id) => CATEGORY_MAP[id] ?? null;

export const getCategoryCount = (categoryId) =>
  categoryId === "all"
    ? EXPERIMENTS.length
    : EXPERIMENTS.filter((experiment) => experiment.category === categoryId).length;

export const getExperimentNumber = (id) => {
  const index = EXPERIMENTS.findIndex((experiment) => experiment.id === id);
  return index === -1 ? null : index + 1;
};

